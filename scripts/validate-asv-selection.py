#!/usr/bin/env python3
"""
validate-asv-selection.py — Pre-check ASV benchmark selectors before launch.

THE PROBLEM THIS PREVENTS:
  When multiple -b selectors are passed to ASV, a typo'd or CR-contaminated
  selector silently matches zero benchmarks. ASV runs the other selectors
  to completion with exit 0, and the shared results file retains stale data
  from a previous run for the zero-matched benchmark. compare-asv.py then
  reads that stale data as if it were fresh, producing a valid-looking but
  false comparison table.

  Stripping CR is necessary but not sufficient: typos, renamed benchmarks,
  and regex errors also cause zero matches. This script catches ALL of those
  before ASV is launched.

WHAT IT DOES:
  1. Loads benchmark metadata from benchmarks.json (ASV's metadata cache,
     generated by `asv check` or `asv run`).
  2. Parses all -b / --bench selectors from the ASV command.
  3. For EACH selector individually, applies ASV's regex matching rules
     against the full benchmark name list.
  4. Any selector with zero matches → exit 1 (fail before launch).
  5. Expands parameter combinations via itertools.product(*params) for each
     matched benchmark, producing the full expected case list.
  6. Writes expected-cases.txt to the run directory.
  7. If no -b selectors are given, expected cases = all benchmarks.

Usage:
    validate-asv-selection.py --benchmarks-file <benchmarks.json> \\
        --run-dir <RUN_DIR> [-- asv-subcommand-and-flags...]

    The ASV command args (everything after --) are parsed for -b/--bench
    selectors. If -- is omitted, all remaining args are parsed.

Exit status:
    0  All selectors match at least one benchmark. expected-cases.txt written.
    1  At least one selector matched zero benchmarks. No launch should proceed.
    2  Could not load benchmarks.json or other setup error.
    64 Usage error.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from itertools import product
from pathlib import Path
from typing import Any


# ---------------------------------------------------------------------------
# Selector parsing
# ---------------------------------------------------------------------------

def extract_selectors(argv: list[str]) -> list[str]:
    """Extract all -b VALUE and --bench VALUE and --bench=VALUE from argv.

    Returns a list of selector strings (may contain duplicates).
    Returns empty list if no -b/--bench found (meaning "all benchmarks").
    """
    selectors: list[str] = []
    i = 0
    while i < len(argv):
        arg = argv[i]
        if arg in ("-b", "--bench"):
            if i + 1 < len(argv):
                selectors.append(argv[i + 1])
                i += 2
                continue
        elif arg.startswith("--bench="):
            selectors.append(arg[len("--bench="):])
        elif arg.startswith("-b="):
            # Non-standard but defensive
            selectors.append(arg[len("-b="):])
        i += 1
    return selectors


# ---------------------------------------------------------------------------
# ASV selector matching
# ---------------------------------------------------------------------------

# ASV treats -b selectors as regex patterns matched against the full
# benchmark name (e.g. "gil.ParallelGroupbyMethods.time_loop"). The match
# is a Python re.search (not fullmatch), so "time_loop" matches any
# benchmark containing that substring.
# See: asv/benchmark.py select_benchmarks logic.

def match_selector(selector: str, benchmark_names: list[str]) -> list[str]:
    """Match a single selector against all benchmark names using ASV's rules.

    ASV uses re.search (substring match), not fullmatch. If the pattern is
    invalid regex, it's treated as a literal string match.
    """
    try:
        pattern = re.compile(selector)
    except re.error:
        # ASV falls back to literal matching on invalid regex
        return [name for name in benchmark_names if selector in name]

    return [name for name in benchmark_names if pattern.search(name)]


# ---------------------------------------------------------------------------
# Parameter expansion
# ---------------------------------------------------------------------------

def expand_cases(bench_name: str, bench_meta: dict[str, Any]) -> list[tuple[str, tuple]]:
    """Expand a benchmark's parameter axes into individual case keys.

    Returns a list of (benchmark_name, params_tuple) pairs.
    params_tuple is () for non-parameterized benchmarks.

    ASV stores params as a list of axes: [['2','4','8'], ['count','last',...]]
    The cartesian product (last axis varies fastest) gives the case ordering.
    """
    params = bench_meta.get("params", [])
    if not params or not isinstance(params, list):
        return [(bench_name, ())]

    # Check if params is a list of lists (parameterized) or flat (single axis)
    if all(isinstance(axis, list) for axis in params):
        if not any(params):  # All axes empty
            return [(bench_name, ())]
        combinations = list(product(*params))
        return [(bench_name, tuple(str(x) for x in combo)) for combo in combinations]
    else:
        # Flat list — treat as single axis
        return [(bench_name, (str(x),)) for x in params]


# ---------------------------------------------------------------------------
# Main logic
# ---------------------------------------------------------------------------

def load_benchmarks(benchmarks_file: Path) -> dict[str, dict[str, Any]]:
    """Load benchmarks.json. Returns {benchmark_name: metadata_dict}.

    benchmarks.json may contain top-level non-benchmark keys like 'version'
    (an integer format version). Filter those out — only dict values are
    benchmark metadata.
    """
    try:
        raw = json.loads(benchmarks_file.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        print(f"error: cannot load benchmarks.json: {exc}", file=sys.stderr)
        sys.exit(2)

    if not isinstance(raw, dict):
        print(f"error: benchmarks.json is not a dict (got {type(raw).__name__})", file=sys.stderr)
        sys.exit(2)

    # Filter: only keep entries whose value is a dict (benchmark metadata).
    # Top-level keys like 'version' (int) are not benchmarks.
    return {k: v for k, v in raw.items() if isinstance(v, dict)}


def validate_and_write(
    benchmarks: dict[str, dict[str, Any]],
    selectors: list[str],
    run_dir: Path,
) -> int:
    """Validate each selector and write expected-cases.txt.

    Returns 0 on success, 1 if any selector has zero matches.
    """
    all_names = sorted(benchmarks.keys())

    if not selectors:
        # No -b given: all benchmarks are expected
        print(f"info: no -b selectors given, all {len(all_names)} benchmarks expected")
        expected_cases: list[tuple[str, tuple]] = []
        for name in all_names:
            expected_cases.extend(expand_cases(name, benchmarks[name]))
    else:
        expected_cases = []
        all_passed = True

        for sel in selectors:
            matches = match_selector(sel, all_names)
            if not matches:
                print(f"FAIL: selector {sel!r} matched ZERO benchmarks", file=sys.stderr)
                print(f"  Available benchmarks containing similar names:", file=sys.stderr)
                # Suggest similar names
                for name in all_names:
                    # Simple similarity: check if any word from selector appears
                    sel_parts = re.split(r"[._]", sel)
                    if any(part and part in name for part in sel_parts):
                        print(f"    {name}", file=sys.stderr)
                all_passed = False
            else:
                print(f"OK: selector {sel!r} matched {len(matches)} benchmark(s):")
                for m in matches:
                    cases = expand_cases(m, benchmarks[m])
                    print(f"  {m} ({len(cases)} case(s))")
                    expected_cases.extend(cases)

        if not all_passed:
            print(f"\nerror: one or more selectors matched zero benchmarks. "
                  f"Aborting before ASV launch to prevent stale-data false positives.",
                  file=sys.stderr)
            return 1

    # Deduplicate expected cases (a benchmark may match multiple selectors)
    seen = set()
    unique_cases: list[tuple[str, tuple]] = []
    for name, params in expected_cases:
        key = (name, params)
        if key not in seen:
            seen.add(key)
            unique_cases.append(key)

    # Write expected-cases.txt
    run_dir.mkdir(parents=True, exist_ok=True)
    cases_file = run_dir / "expected-cases.txt"
    with open(cases_file, "w", encoding="utf-8") as f:
        for name, params in sorted(unique_cases):
            if params:
                f.write(f"{name}({', '.join(str(p) for p in params)})\n")
            else:
                f.write(f"{name}\n")

    print(f"\nWrote {len(unique_cases)} expected cases to {cases_file}")
    return 0


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------

def parse_args(argv: list[str]) -> argparse.Namespace:
    p = argparse.ArgumentParser(
        description="Pre-check ASV benchmark selectors before launch.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        # allow_abbrev=False prevents --bench=... from matching --benchmarks-file
        allow_abbrev=False,
    )
    p.add_argument("--benchmarks-file", required=True, type=Path,
                   help="Path to ASV's benchmarks.json (in the results directory).")
    p.add_argument("--run-dir", required=True, type=Path,
                   help="Run directory where expected-cases.txt will be written.")
    # Use parse_known_args so ASV's own flags (--factor, commit hashes, etc.)
    # don't cause argparse errors. Everything after our options is treated as
    # ASV command args to parse for -b/--bench selectors.
    args, asv_args = p.parse_known_args(argv)
    args.asv_args = asv_args
    return args


def main(argv: list[str]) -> int:
    args = parse_args(argv)

    if not args.benchmarks_file.is_file():
        print(f"error: benchmarks file not found: {args.benchmarks_file}", file=sys.stderr)
        return 2

    benchmarks = load_benchmarks(args.benchmarks_file)

    selectors = extract_selectors(args.asv_args)

    return validate_and_write(benchmarks, selectors, args.run_dir)


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
